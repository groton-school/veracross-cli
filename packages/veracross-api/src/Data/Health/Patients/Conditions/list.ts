import { client, defaults } from '#Client.js';
import { EndpointOptions } from '#types/EndpointOptions.js';
import { ResponseData } from '#types/ResponseBody.js';

export const LIST_SCOPE = 'health.patients.conditions:list';

export type PatientConditionCollection = ResponseData<'list_health_patient_conditions'>;

/** List Health: Patient Conditions */
export async function list({ 
    patient_id, 
    header,
    ...rest
}: EndpointOptions<'list_health_patient_conditions'>): Promise<PatientConditionCollection> {
    const collection: PatientConditionCollection = [];
    let page = !!header && header['X-Page-Number'] ?
        header['X-Page-Number'] :
        1;
    const page_size = !!header && header['X-Page-Size'] ?
        header['X-Page-Size'] :
        defaults().DEFAULT_PAGE_SIZE;
    let done: boolean;
    do {
        const {data,error} = await client().GET('/health/patients/{patient_id}/conditions', {
            params: {
                path : { patient_id,  },
                header: {
                    ...header,
                    'X-Page-Number': page,
                    'X-Page-Size': page_size
                },
                ...rest
            }
        });
        if (error) {
            throw new Error(
                `Error list of PatientCondition at page ${page}`,
                { cause: error }
            );
        }
        collection.push(...data.data);
        page++;
        done = data.data.length < page_size;
    } while (!done);
    return collection;
}